import { escapeHtml } from "@/lib/telegram/bot";

// Тексты, которые бот пишет клиенту в чат.
//
// Правило одно: в чате — событие, содержание — в приложении. Мини-апп
// закрывают сразу после брифа, и без сообщения заявка выглядит потерянной; но
// разбор целиком, вывалённый девятью абзацами в переписку, читается как
// рассылка, а не как работа студии. Поэтому в чат уходит короткое «разбор
// готов» с кнопкой, а сам разбор человек читает на экране — там вёрстка,
// разделы, состояние заявки и кнопка «обсудить».
//
// Формирование текстов вынесено из маршрутов: это чистые функции, их видно в
// тестах, и на длину сообщения Telegram они не жалуются постфактум.

/**
 * Предел одного сообщения — 4096 символов. Держим запас: Telegram считает
 * видимый текст, а у нас в строке живут ещё и HTML-экранирования.
 */
export const MESSAGE_LIMIT = 3800;

/**
 * Собирает сообщение из абзацев и молча отбрасывает тот, что уже не влезает.
 * Тексты короткие, до предела им далеко — это страховка на случай, когда в
 * сообщение попадёт что-то пользовательское вроде имени.
 */
function join(blocks: string[]): string {
  let text = "";
  for (const block of blocks) {
    if (!block) continue;
    const next = text ? `${text}\n\n${block}` : block;
    if (next.length > MESSAGE_LIMIT) continue;
    text = next;
  }
  return text;
}

/**
 * Разбор готов.
 *
 * Сообщение намеренно короткое: оно отмечает событие и ведёт в приложение. Там
 * же человек увидит и состояние заявки — дублировать его сюда незачем.
 */
export function analysisReadyMessage(): string {
  return join([
    "<b>Бриф принят, разбор готов</b>",
    "Мы разобрали задачу по вашим ответам: что поняли, какой формат подходит, как может выглядеть структура и что стоит обсудить. Всё это ждёт вас в приложении.",
    "Заявка на рассмотрении — посмотрим её командой и вернёмся с ответом в этот чат.",
  ]);
}

/**
 * Бриф дошёл, а разбор — нет. Молчать здесь нельзя тем более: на экране
 * человек в этот момент видит ошибку.
 */
export function analysisFailedMessage(): string {
  return join([
    "<b>Бриф получен</b>",
    "Ответы у нас, заявка на месте. Автоматический разбор собрать не удалось — посмотрим задачу руками и напишем в этом чате.",
  ]);
}

export type ChatLeadStatus = "new" | "qualified" | "in_work" | "won" | "lost";

export type ChatLeadState = {
  status: ChatLeadStatus;
  hasAnalysis: boolean;
};

/**
 * Ответ на /start.
 *
 * Первое сообщение бота — единственное место, где мы объясняем, что вообще
 * происходит: до него человек видит пустой чат и кнопку меню без подписи.
 * Текст зависит от того, что у человека уже есть: приглашение к брифу тому,
 * кто пришёл впервые, и состояние заявки тому, кто её уже отправил.
 */
export function greetingMessage(firstName: string | null, lead: ChatLeadState | null): string {
  const hello = firstName ? `Здравствуйте, ${escapeHtml(firstName)}!` : "Здравствуйте!";

  if (lead && (lead.status === "in_work" || lead.status === "won")) {
    return join([
      `${hello} Ваш проект в работе.`,
      "Этапы, задачи и согласования — в приложении. Там же видно, что мы ждём от вас.",
    ]);
  }

  if (lead && (lead.status === "new" || lead.status === "qualified")) {
    return join([
      `${hello} Ваш бриф у нас.`,
      lead.hasAnalysis
        ? "Разбор готов — его можно перечитать в приложении. Там же одна кнопка, чтобы позвать нас обсудить задачу."
        : "Мы смотрим задачу и вернёмся с ответом в этот чат. Состояние заявки видно в приложении.",
    ]);
  }

  return join([
    `${hello} Это <b>nyraflow desk</b> — рабочий стол студии в Telegram.`,
    "Мы делаем лендинги, веб-сервисы и Telegram Mini App, а также сайты с AI-автоматизацией.",
    "Расскажите о задаче: восемь вопросов, пара минут. В ответ соберём предварительный разбор — что мы поняли, какой формат подходит, как может выглядеть структура, на что смотреть внимательно и что стоит обсудить.",
    "Разбор ни к чему не обязывает: это повод для разговора, а не счёт.",
    "Нажмите кнопку ниже, чтобы начать.",
  ]);
}

/** Ответ на /help — коротко о том, что бот умеет. */
export function helpMessage(): string {
  return join([
    "<b>Как это работает</b>",
    "1. Открываете приложение и отвечаете на восемь вопросов о задаче.\n2. Читаете предварительный разбор на экране — сюда придёт короткое «готово».\n3. Нажимаете «Обсудить разбор с командой» — и мы пишем вам в этот чат.",
    "Команды: /start — начать заново, /help — это сообщение.",
    "Если удобнее словами — напишите прямо в этот чат, мы прочитаем.",
  ]);
}

/**
 * Ответ на любой другой текст. Бот не ведёт переписку — её ведёт команда,
 * поэтому здесь важно не изобразить диалог, а сказать, что сообщение дошло.
 */
export function fallbackMessage(): string {
  return join([
    "Сообщение получено — команда его увидит.",
    "Чтобы мы ответили по делу, лучше пройти бриф: восемь вопросов, и на руках будет предварительный разбор задачи.",
  ]);
}

/**
 * Команда из текста сообщения: `/start@nyraflow_bot payload` → `start`.
 * Всё, что не начинается со слеша, командой не считается.
 */
export function parseCommand(text: string): string | null {
  const first = text.trim().split(/\s+/)[0] ?? "";
  if (!first.startsWith("/")) return null;
  return first.slice(1).split("@")[0]!.toLowerCase() || null;
}
