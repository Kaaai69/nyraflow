// Сборка промпта.
//
// Два принципа. Первый: модель обязана рекомендовать один из форматов студии,
// а не абстрактное решение — иначе разбор противоречит тому, что мы продаём.
// Второй: запрет на общие формулировки. На тесте модель без такого запрета
// выдавала риски вида «конкуренция в Москве», которые подходят кому угодно и
// не стоят ничего.

/**
 * Разряды разделяются вручную, а не через toLocaleString: результат промпта
 * не должен зависеть от того, какая ICU-локаль собрана в рантайме. Иначе
 * «30 000» однажды молча станет «30,000».
 */
function formatPrice(value: number): string {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}

const PRODUCT_LINES = studioProducts
