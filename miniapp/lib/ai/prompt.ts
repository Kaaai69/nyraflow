/**
 * Убирает из ответов контакты перед отправкой в модель: телефоны, почты,
 * телеграм-ники и ссылки. Модель они не улучшают, а бесплатные тарифы могут
 * учиться на переданных данных — контакты клиента там лишние.
 */
export function sanitizeAnswer(value: string): string {
  return value
    .replace(/[\w.+-]+@[\w-]+\.[\w.]+/g, "[почта]")
    .replace(/\+?\d[\d\s()-]{9,}\d/g, "[телефон]")
    .replace(/@[A-Za-z][\w]{3,}/g, "[ник]")
    .replace(/https?:\/\/\S+/g, "[ссылка]");
}

export function buildUserPrompt(answers: BriefAnswers): string {
  const lines: string[] = [];

  for (const question of briefQuestions) {
    const answer = answers[question.id]?.trim();
    if (!answer) continue;
    lines.push(`${question.title}\n${sanitizeAnswer(answer)}`);
  }

  return lines.join("\n\n");
}
